alter table public.vendas alter column id set generated by default;
alter table public.venda_itens alter column id set generated by default;
alter table public.venda_pagamentos alter column id set generated by default;
alter table public.estoque_movimentos alter column id set generated by default;
alter table public.eventos alter column id set generated by default;
alter table public.acessos alter column id set generated by default;

-- Hash SHA1 do PHP; o login troca pela senha do Auth no primeiro acesso e apaga a linha.
-- Só service role (sem policies, sem grants para anon/authenticated).
create table public.senhas_legado (
  user_id uuid primary key references auth.users on delete cascade,
  sha1 text not null
);
alter table public.senhas_legado enable row level security;
revoke all on public.senhas_legado from anon, authenticated;
grant select, insert, update, delete on public.senhas_legado to service_role;

-- Depois de inserir com IDs explícitos, a sequência precisa continuar do maior ID
create function public.ajustar_sequencias() returns void
language plpgsql security definer set search_path = '' as $$
declare t text;
begin
  foreach t in array array['lojas', 'produtos', 'vendas', 'venda_itens', 'venda_pagamentos',
                           'estoque_movimentos', 'eventos', 'acessos'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
                   'public.' || t, t);
  end loop;
end $$;
revoke all on function public.ajustar_sequencias() from public, anon, authenticated;
grant execute on function public.ajustar_sequencias() to service_role;
